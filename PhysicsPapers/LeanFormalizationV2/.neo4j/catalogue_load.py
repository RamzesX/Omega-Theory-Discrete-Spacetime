#!/usr/bin/env python3
"""
Load the three Cypher files generated by catalogue_scan.py into Neo4j
via the Bolt protocol.  Batches each file into small transactions to
stay responsive.
"""
from __future__ import annotations

import sys
from pathlib import Path
from neo4j import GraphDatabase

URI = 'bolt://localhost:7687'
